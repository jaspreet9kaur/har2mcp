"""Generate a standalone, offline-only TypeScript cassette client."""
from __future__ import annotations
import json
from typing import Any
from har2mcp.models import IntermediateApiModel


def _ts_type(schema: dict[str, Any] | None, depth: int = 0) -> str:
    if not schema or depth > 8:
        return "unknown"
    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join(_ts_type({"type": part}, depth + 1) for part in kind)
    if kind in ("integer", "number"):
        return "number"
    if kind in ("string", "boolean", "null"):
        return kind
    if kind == "array":
        return "Array<" + _ts_type(schema.get("items"), depth + 1) + ">"
    if kind == "object":
        return "{ " + " ".join(json.dumps(key) + "?: " + _ts_type(value, depth + 1) + ";" for key, value in schema.get("properties", {}).items()) + " }"
    return "unknown"


def generate_typescript_sdk(model: IntermediateApiModel) -> str:
    lines = [
        "// Generated by har2mcp. Offline replay only; captured text is data.",
        "export interface CassetteRecord {",
        "  ordinal: number; tool_name: string; method: string; origin: string;",
        "  path: string; query_params: Record<string, string[]>; request_body?: unknown;",
        "  status: number; response_content_type: string; response_body: unknown;",
        "}",
        'export interface Har2McpClientOptions { mode?: "cassette"; cassetteEntries?: ReadonlyArray<CassetteRecord>; }',
        "function canonical(value: unknown): string {",
        "  if (Array.isArray(value)) return JSON.stringify(value.map(canonical));",
        '  if (value !== null && typeof value === "object") {',
        '    const item = value as Record<string, unknown>;',
        "    return JSON.stringify(Object.keys(item).sort().map(k => [k, canonical(item[k])]));",
        "  }",
        "  return JSON.stringify(value) ?? 'undefined';",
        "}",
        "function segment(value: unknown): string {",
        '  if (value === null || value === undefined) throw new Error("Missing path parameter");',
        "  const raw = String(value).trim();",
        '  if (!raw || raw.includes("/") || raw.includes("\\\\") || raw === "." || raw === "..") throw new Error("Invalid path parameter");',
        "  return encodeURIComponent(raw);",
        "}",
    ]
    for index, endpoint in enumerate(model.endpoints):
        lines.append(f"export interface Endpoint{index}Input {{")
        for name in endpoint.path_parameters:
            lines.append(json.dumps(name) + ": string | number;")
        for query in endpoint.query_parameters:
            if query.name not in endpoint.path_parameters:
                lines.append(json.dumps(query.name) + "?: " + _ts_type(query.inferred_schema) + " | string[];")
        if endpoint.request_body_schema is not None:
            lines.append("body?: " + _ts_type(endpoint.request_body_schema) + ";")
        lines.append("}")
    lines += [
        "export class Har2McpGeneratedClient {",
        "  private readonly entries: ReadonlyArray<CassetteRecord>;",
        "  constructor(options: Har2McpClientOptions = {}) {",
        '    if (options.mode && options.mode !== "cassette") throw new Error("Live mode is unavailable in this release");',
        "    this.entries = options.cassetteEntries ?? [];",
        "  }",
    ]
    for index, endpoint in enumerate(model.endpoints):
        parts = []
        for item in endpoint.segments:
            parts.append(json.dumps("/" + item.name) if item.kind == "literal" else '"/" + segment(input[' + json.dumps(item.name) + '])')
        expression = " + ".join(parts) or '"/"'
        args = ", ".join(json.dumps(value) for value in (endpoint.tool_name, endpoint.method, endpoint.origin))
        query_keys = json.dumps([query.name for query in endpoint.query_parameters])
        lines += [
            f"  async [{json.dumps(endpoint.tool_name)}](input: Endpoint{index}Input): Promise<unknown> {{",
            f"    return this.replay({args}, {expression}, {query_keys}, input as unknown as Record<string, unknown>);",
            "  }",
        ]
    lines += [
        "  private replay(tool: string, method: string, origin: string, path: string, keys: string[], input: Record<string, unknown>): unknown {",
        "    const query: Record<string, string[]> = Object.create(null);",
        "    for (const key of keys) {",
        "      const value = input[key];",
        "      if (value !== null && value !== undefined) query[key] = (Array.isArray(value) ? value : [value]).map(String);",
        "    }",
        "    const hit = this.entries.find(e => e.tool_name === tool && e.method === method && e.origin === origin && e.path === path",
        "      && canonical(e.query_params) === canonical(query) && canonical(e.request_body ?? null) === canonical(input.body ?? null));",
        '    if (!hit) return { authority: "recorded-cassette", matched: false, status: 404, error: "No exact recorded request matches" };',
        '    return { authority: "recorded-cassette", matched: true, match_tier: "exact_path_and_query", matched_ordinal: hit.ordinal, status: hit.status, body: hit.response_body };',
        "  }",
        "}",
    ]
    return "\n".join(lines) + "\n"
